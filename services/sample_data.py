def is_sample_material_loaded(db: DatabaseManager) -> bool:
    """Returns True if the sample DBMS documents are already loaded in the database."""
    with db._get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute(
            "SELECT COUNT(*) FROM documents WHERE filename IN ('DBMS_Syllabus_Demo.pdf', 'DBMS_Lecture_Notes_Demo.pdf')"
        )
        count = cursor.fetchone()[0]
        return count >= 2


def populate_sample_dbms_data(db: DatabaseManager, force: bool = False) -> bool:
    """
    Idempotently populates SQLite database with sample syllabus and lecture notes.
    If already loaded and force is False, returns False without modifying data.
    If force is True, replaces existing sample documents cleanly, guaranteeing exactly 2 documents and 6 chunks.
    """
    if is_sample_material_loaded(db) and not force:
        return False

    # 1. Syllabus Document (2 pages, 2 chunks)
    syllabus_chunks = []
    chunk_idx = 0
    for page in SAMPLE_DBMS_SYLLABUS:
        syllabus_chunks.append({
            "chunk_index": chunk_idx,
            "page_number": page["page_number"],
            "text": page["text"],
            "source": "DBMS_Syllabus_Demo.pdf",
        })
        chunk_idx += 1

    db.save_document(
        filename="DBMS_Syllabus_Demo.pdf",
        file_type="PDF (Demo Syllabus)",
        num_chunks=len(syllabus_chunks),
        num_pages=len(SAMPLE_DBMS_SYLLABUS),
        chunks=syllabus_chunks,
        is_sample=True,
    )

    # 2. Notes Document (4 pages, 4 chunks)
    notes_chunks = []
    chunk_idx = 0
    for page in SAMPLE_DBMS_NOTES:
        notes_chunks.append({
            "chunk_index": chunk_idx,
            "page_number": page["page_number"],
            "text": page["text"],
            "source": "DBMS_Lecture_Notes_Demo.pdf",
        })
        chunk_idx += 1

    db.save_document(
        filename="DBMS_Lecture_Notes_Demo.pdf",
        file_type="PDF (Demo Notes)",
        num_chunks=len(notes_chunks),
        num_pages=len(SAMPLE_DBMS_NOTES),
        chunks=notes_chunks,
        is_sample=True,
    )

    return True


